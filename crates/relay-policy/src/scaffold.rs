//! Automatic Cedar policy and schema scaffolding for MCP servers.
//!
//! Provides deterministic semantic classification of MCP tool definitions,
//! generates strongly typed Cedar schemas and default-deny policies, and enforces
//! pre-flight in-memory validation via the Cedar policy compiler.

use cedar_policy::{PolicySet, Schema};
use relay_domain::PolicyError;
use serde::{Deserialize, Serialize};

/// Tool definition discovered from an MCP server (`tools/list`).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ToolDefinition {
    /// Name of the tool as reported by the MCP server.
    pub name: String,
    /// Human-readable description of the tool.
    #[serde(default)]
    pub description: Option<String>,
    /// JSON Schema defining the tool's input arguments.
    #[serde(default)]
    pub input_schema: serde_json::Value,
}

/// Semantic risk tier assigned to a tool based on name and description heuristics.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ToolTier {
    /// Safe, non-mutating operations permitted by default for non-sensitive resources.
    ReadOnly,
    /// State-mutating operations requiring explicit approval or fine-grained scoping.
    Mutation,
    /// High-risk or destructive operations requiring mandatory step-up human approval.
    Destructive,
}

impl ToolTier {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::ReadOnly => "ReadOnly",
            Self::Mutation => "Mutation",
            Self::Destructive => "Destructive",
        }
    }
}

/// Classifies an MCP tool into a `ToolTier` using verb and keyword heuristics.
pub fn classify_tool(tool: &ToolDefinition) -> ToolTier {
    let name_lower = tool.name.to_lowercase();
    let desc_lower = tool.description.as_deref().unwrap_or("").to_lowercase();

    // 1. Check for destructive / execution indicators (highest risk)
    const DESTRUCTIVE_KEYWORDS: &[&str] = &[
        "delete",
        "remove",
        "drop",
        "truncate",
        "kill",
        "destroy",
        "purge",
        "erase",
        "format",
        "terminate",
        "exec",
        "execute",
        "shell",
        "bash",
        "sh",
        "cmd",
        "command",
        "spawn",
        "eval",
    ];

    for kw in DESTRUCTIVE_KEYWORDS {
        if name_lower.contains(kw) || desc_lower.contains(kw) {
            return ToolTier::Destructive;
        }
    }

    // 2. Check for read-only indicators
    const READ_KEYWORDS: &[&str] = &[
        "read",
        "get",
        "list",
        "search",
        "fetch",
        "describe",
        "find",
        "inspect",
        "check",
        "scan",
        "view",
        "stat",
        "cat",
        "peek",
        "query_select",
    ];

    let mut is_read = false;
    for kw in READ_KEYWORDS {
        if name_lower.starts_with(kw)
            || name_lower.ends_with(kw)
            || name_lower.contains(&format!("_{kw}"))
            || name_lower.contains(&format!("{kw}_"))
        {
            is_read = true;
            break;
        }
    }

    // 3. Check for mutation indicators
    const MUTATION_KEYWORDS: &[&str] = &[
        "write", "create", "update", "set", "put", "edit", "patch", "send", "post", "insert",
        "alter", "append", "modify", "replace", "upload", "publish",
    ];

    for kw in MUTATION_KEYWORDS {
        if name_lower.contains(kw) || desc_lower.contains(kw) {
            return ToolTier::Mutation;
        }
    }

    if is_read {
        ToolTier::ReadOnly
    } else {
        // Safe default: unclassified tools require mutation tier (approval-gated)
        ToolTier::Mutation
    }
}

/// Normalizes a tool name into a valid Cedar action identifier.
pub fn sanitize_action_name(name: &str) -> String {
    name.replace([':', '/'], ".").trim_matches('.').to_string()
}

/// Generates a Cedar schema in `.cedarschema` format for the provided MCP tools.
pub fn generate_cedar_schema(tools: &[ToolDefinition]) -> String {
    let mut out = String::with_capacity(2048);

    out.push_str("// Auto-generated Cedar Schema for Relay MCP Gateway\n");
    out.push_str("// Generated by: relay policy scaffold\n\n");
    out.push_str("namespace Relay {\n");
    out.push_str("    entity Agent = {\n");
    out.push_str("        agent_id?: String,\n");
    out.push_str("        session_id?: String,\n");
    out.push_str("    };\n\n");
    out.push_str("    entity Resource = {\n");
    out.push_str("        uri?: String,\n");
    out.push_str("        environment?: String,\n");
    out.push_str("    };\n\n");
    out.push_str("    type ActionContext = {\n");
    out.push_str("        path?: String,\n");
    out.push_str("        query?: String,\n");
    out.push_str("        tool?: String,\n");
    out.push_str("        operation?: String,\n");
    out.push_str("        action_hash?: String,\n");
    out.push_str("        has_approval?: Bool,\n");
    out.push_str("        is_destructive?: Bool,\n");
    out.push_str("    };\n\n");

    out.push_str(
        "    // -------------------------------------------------------------------------\n",
    );
    out.push_str("    // Discovered MCP Tool Actions\n");
    out.push_str(
        "    // -------------------------------------------------------------------------\n",
    );

    for tool in tools {
        let action_name = sanitize_action_name(&tool.name);
        out.push_str(&format!("    action \"{}\" appliesTo {{\n", action_name));
        out.push_str("        principal: [Agent],\n");
        out.push_str("        resource: [Resource],\n");
        out.push_str("        context: ActionContext,\n");
        out.push_str("    };\n\n");
    }

    out.push_str("}\n");
    out
}

/// Generates a Cedar policy set (`.cedar`) enforcing default-deny, sensitive path protection,
/// and semantic tier-based permits.
pub fn generate_cedar_policy(tools: &[ToolDefinition]) -> String {
    let mut out = String::with_capacity(3072);

    out.push_str(
        "// =============================================================================\n",
    );
    out.push_str("// Relay Cedar Security Policies\n");
    out.push_str("// Auto-generated by: relay policy scaffold\n");
    out.push_str("// Strict Default-Deny Architecture (SI-004)\n");
    out.push_str(
        "// =============================================================================\n\n",
    );

    out.push_str(
        "// -----------------------------------------------------------------------------\n",
    );
    out.push_str("// Universal Defense-in-Depth: Block Sensitive Credential & System Paths\n");
    out.push_str(
        "// -----------------------------------------------------------------------------\n",
    );
    out.push_str("forbid(\n");
    out.push_str("    principal,\n");
    out.push_str("    action,\n");
    out.push_str("    resource in Relay::Resource::\"~/.ssh\"\n");
    out.push_str(");\n\n");

    out.push_str("forbid(\n");
    out.push_str("    principal,\n");
    out.push_str("    action,\n");
    out.push_str("    resource in Relay::Resource::\"~/.aws\"\n");
    out.push_str(");\n\n");

    out.push_str("forbid(\n");
    out.push_str("    principal,\n");
    out.push_str("    action,\n");
    out.push_str("    resource in Relay::Resource::\".env\"\n");
    out.push_str(");\n\n");

    out.push_str("forbid(\n");
    out.push_str("    principal,\n");
    out.push_str("    action,\n");
    out.push_str("    resource in Relay::Resource::\"/etc/shadow\"\n");
    out.push_str(");\n\n");

    out.push_str(
        "// -----------------------------------------------------------------------------\n",
    );
    out.push_str("// Discovered Tool Governance Rules\n");
    out.push_str(
        "// -----------------------------------------------------------------------------\n\n",
    );

    for tool in tools {
        let action_name = sanitize_action_name(&tool.name);
        let tier = classify_tool(tool);
        let desc = tool
            .description
            .as_deref()
            .unwrap_or("No description provided");

        match tier {
            ToolTier::ReadOnly => {
                out.push_str(&format!("// [READ-ONLY] Tool: {} — {}\n", tool.name, desc));
                out.push_str("permit(\n");
                out.push_str("    principal,\n");
                out.push_str(&format!(
                    "    action == Relay::Action::\"{}\",\n",
                    action_name
                ));
                out.push_str("    resource\n");
                out.push_str(");\n\n");
            }
            ToolTier::Mutation => {
                out.push_str(&format!(
                    "// [MUTATION] Tool: {} — {} (Requires approval)\n",
                    tool.name, desc
                ));
                out.push_str("@advice(\"REQUIRE_HUMAN_APPROVAL\")\n");
                out.push_str(&format!(
                    "@approval_required(\"Operator approval required for mutation: {}\")\n",
                    tool.name
                ));
                out.push_str("permit(\n");
                out.push_str("    principal,\n");
                out.push_str(&format!(
                    "    action == Relay::Action::\"{}\",\n",
                    action_name
                ));
                out.push_str("    resource\n");
                out.push_str(");\n\n");
            }
            ToolTier::Destructive => {
                out.push_str(&format!(
                    "// [DESTRUCTIVE] Tool: {} — {} (Requires mandatory approval)\n",
                    tool.name, desc
                ));
                out.push_str("@advice(\"REQUIRE_HUMAN_APPROVAL\")\n");
                out.push_str(&format!(
                    "@approval_required(\"Mandatory operator approval required for destructive operation: {}\")\n",
                    tool.name
                ));
                out.push_str("permit(\n");
                out.push_str("    principal,\n");
                out.push_str(&format!(
                    "    action == Relay::Action::\"{}\",\n",
                    action_name
                ));
                out.push_str("    resource\n");
                out.push_str(");\n\n");
            }
        }
    }

    out
}

/// Generates and pre-flight compiles a complete Cedar policy bundle from tool definitions.
///
/// Returns `(policy_source, schema_source)` if and only if both compile and validate cleanly
/// against the AWS Cedar engine with zero errors.
pub fn generate_and_validate_bundle(
    tools: &[ToolDefinition],
) -> Result<(String, String, PolicySet, Schema), PolicyError> {
    let schema_src = generate_cedar_schema(tools);
    let policy_src = generate_cedar_policy(tools);

    // Pre-flight in-memory compilation & validation
    let schema = crate::schema::parse_schema(&schema_src)?;
    let (policy_set, _digest) = crate::loader::PolicyLoader::load_from_str(&policy_src, &schema)?;

    Ok((policy_src, schema_src, policy_set, schema))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn test_classify_tool_tiers() {
        let read_tool = ToolDefinition {
            name: "read_file".to_string(),
            description: Some("Read file contents from disk".to_string()),
            input_schema: json!({ "type": "object" }),
        };
        assert_eq!(classify_tool(&read_tool), ToolTier::ReadOnly);

        let write_tool = ToolDefinition {
            name: "write_file".to_string(),
            description: Some("Create or overwrite a file on disk".to_string()),
            input_schema: json!({ "type": "object" }),
        };
        assert_eq!(classify_tool(&write_tool), ToolTier::Mutation);

        let delete_tool = ToolDefinition {
            name: "delete_directory".to_string(),
            description: Some("Recursively remove a directory".to_string()),
            input_schema: json!({ "type": "object" }),
        };
        assert_eq!(classify_tool(&delete_tool), ToolTier::Destructive);

        let exec_tool = ToolDefinition {
            name: "run_shell_command".to_string(),
            description: Some("Execute bash command".to_string()),
            input_schema: json!({ "type": "object" }),
        };
        assert_eq!(classify_tool(&exec_tool), ToolTier::Destructive);
    }

    #[test]
    fn test_bundle_generation_and_compilation() {
        let tools = vec![
            ToolDefinition {
                name: "fs_read".to_string(),
                description: Some("Read file".to_string()),
                input_schema: json!({}),
            },
            ToolDefinition {
                name: "fs_write".to_string(),
                description: Some("Write file".to_string()),
                input_schema: json!({}),
            },
            ToolDefinition {
                name: "db_drop_table".to_string(),
                description: Some("Drop database table".to_string()),
                input_schema: json!({}),
            },
        ];

        let res = generate_and_validate_bundle(&tools);
        assert!(
            res.is_ok(),
            "Generated bundle must compile cleanly: {:?}",
            res.err()
        );

        let (policy_src, schema_src, _, _) = res.unwrap();
        assert!(policy_src.contains("fs_read"));
        assert!(policy_src.contains("fs_write"));
        assert!(policy_src.contains("db_drop_table"));
        assert!(policy_src.contains("~/.ssh"));
        assert!(schema_src.contains("action \"fs_read\""));
    }
}
